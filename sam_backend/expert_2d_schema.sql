-- New instrument is independent of all earlier data; no historical row is changed.
CREATE TABLE IF NOT EXISTS expert_2d_ratings (
 mode TEXT NOT NULL CHECK(mode IN ('production','test')),
 rater TEXT NOT NULL CHECK(rater IN ('R1','R2','R3')),
 profile TEXT NOT NULL,
 trial_index INTEGER NOT NULL CHECK(trial_index BETWEEN 1 AND 24),
 atmosphere_valence INTEGER NOT NULL CHECK(atmosphere_valence BETWEEN 1 AND 9),
 atmosphere_arousal INTEGER NOT NULL CHECK(atmosphere_arousal BETWEEN 1 AND 9),
 atmosphere_dominance INTEGER NOT NULL CHECK(atmosphere_dominance BETWEEN 1 AND 9),
 intended_valence INTEGER NOT NULL CHECK(intended_valence BETWEEN 1 AND 9),
 intended_arousal INTEGER NOT NULL CHECK(intended_arousal BETWEEN 1 AND 9),
 intended_dominance INTEGER NOT NULL CHECK(intended_dominance BETWEEN 1 AND 9),
 confidence INTEGER NOT NULL CHECK(confidence BETWEEN 1 AND 7),
 visual_elements TEXT NOT NULL CHECK(length(btrim(visual_elements)) BETWEEN 1 AND 2000),
 personal_meaning TEXT NOT NULL CHECK(length(btrim(personal_meaning)) BETWEEN 1 AND 2000),
 question_order TEXT NOT NULL CHECK(question_order IN ('atmosphere_first','intention_first')),
 view_ms INTEGER NOT NULL,
 submitted_at_utc TEXT NOT NULL,
 protocol TEXT NOT NULL,
 image_sha256 TEXT NOT NULL,
 PRIMARY KEY(mode,rater,profile),
 UNIQUE(mode,rater,trial_index)
);
CREATE TABLE IF NOT EXISTS expert_2d_stage2_ratings (
 mode TEXT NOT NULL CHECK(mode IN ('production','test')),
 rater TEXT NOT NULL CHECK(rater IN ('R1','R2','R3')),
 profile TEXT NOT NULL CHECK(profile IN ('P1','P2','P3','P5','P6','P7','P8','P12','P22','P23','P24')),
 trial_index INTEGER NOT NULL CHECK(trial_index BETWEEN 1 AND 11),
 intended_valence INTEGER NOT NULL CHECK(intended_valence BETWEEN 1 AND 9),
 intended_arousal INTEGER NOT NULL CHECK(intended_arousal BETWEEN 1 AND 9),
 intended_dominance INTEGER NOT NULL CHECK(intended_dominance BETWEEN 1 AND 9),
 confidence INTEGER NOT NULL CHECK(confidence BETWEEN 1 AND 7),
 view_ms INTEGER NOT NULL,
 submitted_at_utc TEXT NOT NULL,
 protocol TEXT NOT NULL,
 image_sha256 TEXT NOT NULL,
 explanation_version TEXT NOT NULL,
 explanation_text TEXT NOT NULL,
 explanation_sha256 TEXT NOT NULL,
 baseline_json TEXT NOT NULL CHECK(jsonb_typeof(baseline_json::jsonb) = 'object'),
 PRIMARY KEY(mode,rater,profile),
 UNIQUE(mode,rater,trial_index),
 FOREIGN KEY(mode,rater,profile) REFERENCES expert_2d_ratings(mode,rater,profile)
);
